const DICTS: Record<Lang, Record<string, string>> = { en, hi, pa };

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translate;
}

const Ctx = createContext<I18n>({ lang: 'en', setLang: () => {}, t: (k) => en[k] ?? k });

function deviceLang(): Lang {
  try {
    const tag = (typeof navigator !== 'undefined' ? navigator.language : '') || '';
    if (tag.startsWith('hi')) return 'hi';
    if (tag.startsWith('pa')) return 'pa';
  } catch {
    // no navigator on native; the stored choice or English applies
  }
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((v) => setLangState(v === 'hi' || v === 'pa' || v === 'en' ? v : deviceLang()))
      .catch(() => setLangState(deviceLang()));
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);
  const t = useCallback<Translate>(
    (key, vars) => {
      let s = DICTS[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  return useContext(Ctx);
}

export function useT(): Translate {
  return useContext(Ctx).t;
}

